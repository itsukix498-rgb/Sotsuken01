"""使い方：はじめての人向けに、各ステップの使い方とAIの判定結果の見方を説明する。"""

import streamlit as st

from ui_ai import DAILY_LIMIT, MAX_AI_PAPERS
from ui_common import UPLOAD_PAGE, flow, go_to_step, page_title

page_title("Guide", "使い方")
st.write("このアプリは、学習分析・教育データマイニングの論文を読んで、"
         "**ほかの研究に使える教育データセット**（学習の記録、成績、アンケートなど）と、その入手方法を見つけます。")
flow()

st.subheader("論文を検索して調べる（STEP 1〜4）")
st.markdown(f"""
1. **論文を検索**：会議・学会誌と年を選び、必要ならタイトルのキーワードで絞り込みます。
   国際会議（LAK・EDM・AIED）と、国内の学会誌・大会（J-STAGE）に対応しています。
   同じ画面を開いている間は、前に検索した結果を「検索の履歴」から開き直せます。
2. **論文を選ぶ**：一覧から、URLを抜き出したい論文にチェックを付けます。
   PDFを自動で取得できない論文（LAK など）は、論文ページからPDFを保存し、「手元の論文を調べる」で処理できます。
3. **URLを抽出**：選んだ論文のPDFを1本ずつ取得し、本文とリンクに含まれるURLを一覧にします（1回30本まで。J-STAGE は10本まで）。
   URLの一覧はCSVで保存できます。
4. **AIで判定**：取得した論文を AI が読み、**手に入れられる教育データセットがあるか**と、その**名前・URL・入手方法**を判定します。
   判定する論文はチェックで選びます（1回{MAX_AI_PAPERS}本まで）。
""")
if st.button("論文を検索する", type="primary", key="guide_search"):
    go_to_step(1)

st.subheader("AIの判定結果の見方")
st.markdown("""
論文ごとに、次の4つに分けて表示します。

| 分類 | 意味 |
|---|---|
| 公開 | 誰でも、またはアカウント登録をすればデータを入手できる |
| 要申請 | 著者などに頼めばデータを提供してもらえる |
| 非公開 | 読者が入手できるデータはない（大学内だけのデータなど） |
| 不明 | 本文からは判断できない（「判定不能」は、AIの答えが決められた形にならなかったもの） |

データセットごとの**入手方法**は、「公開（ダウンロードできる）」「要ログイン（アカウント登録が必要）」「要申請（著者に連絡する）」の3つです。
**根拠の文**は、AIが判断の手がかりにした論文中の文です。

数えるのは**教育に関係するデータセット**だけです（学習の記録、成績・解答、作文や掲示板への投稿、学生へのアンケート、試験問題・教材など）。
画像やニュース記事など、教育と関係のない一般的なデータセットや、プログラム・学習済みモデルは数えません。
""")

st.subheader("注意すること")
st.markdown(f"""
- **AIは間違えることがあります。** 根拠の文とリンク先を必ず確かめてください。
- **AIで判定できるのは英語の論文だけです。** 日本語の論文はURLの抽出までで、AIの判定の対象外です（まだ正しく判定できることを確かめていないため）。
- 論文に名前しか書かれていないデータセット（参考文献だけのもの）は、URLが空欄になります。参考文献をたどって探してください。
- AIには、論文の本文の一部（URLの前後の文と、データについて書かれた文）とURLだけを送ります（Google Gemini、無料枠）。
  無料枠のため、送った内容が Google のサービス改善に使われることがあります。
- AIの判定は、アプリを使う全員の合計で1日{DAILY_LIMIT}本までです。
- 取得・アップロードしたPDFは保存しません。
""")

st.subheader("手元の論文を調べる")
st.markdown("""
持っている論文のPDFをアップロードすると、URLを一覧にします。
英語の論文は、**公開済みの論文であることを確認したうえで**、AIでも判定できます。
投稿前の原稿や研究室内の資料は、外部のAIに送らないでください。
""")
if st.button("PDFをアップロードする", key="guide_upload"):
    st.switch_page(UPLOAD_PAGE)

st.subheader("データの出典")
st.markdown("論文の情報：Crossref、Zenodo、OpenAlex、[J-STAGE](https://www.jstage.jst.go.jp/)（Powered by J-STAGE）"
            "　／　AI：Google Gemini")
